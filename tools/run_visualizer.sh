#!/bin/bash
# Скрипт для запуска визуализации торговых данных

# Переходим в корневую папку проекта
cd "$(dirname "$0")/.."

# Активируем виртуальное окружение
source env/bin/activate

echo "🚀 Запуск визуализации торговых данных"
echo "====================================================="
echo "📊 Инструмент: FUTIMOEXF000 (Фьючерс на индекс МосБиржи)"
echo "🎯 Параметры стратегии: MACD(6,12,7) ATR(10) L(6-18) P(0.15)"
echo "🌐 Веб-интерфейс: http://127.0.0.1:8050"
echo ""

# Проверяем наличие .env файла
if [ ! -f .env ]; then
    echo "⚠️  Файл .env не найден!"
    echo "Создайте файл .env с переменными:"
    echo "TINKOFF_TOKEN=your_token"
    echo "TINKOFF_ACCOUNT=your_account_id"
    echo "SANDBOX_TOKEN=your_sandbox_token"
    echo ""
    echo "Будет использована симуляция данных"
    echo ""
else
    echo "✅ Файл .env найден, будут использованы реальные данные"
    echo ""
fi

echo "✨ Возможности:"
echo "   • Реальные данные через Tinkoff API"
echo "   • Автоматическое переключение на симуляцию при ошибках"
echo "   • Интеграция с SignalManager"
echo "   • MACD индикаторы в реальном времени"
echo "   • Торговые сигналы на основе реальных данных"
echo "   • Современный адаптивный интерфейс"
echo ""

# Запускаем визуализацию с реальными данными
python tools/market_visualizer.py
